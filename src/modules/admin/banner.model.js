import mongoose from "mongoose";


const bannerSchema =
    new mongoose.Schema(

        {

            /*
            |--------------------------------------------------------------------------
            | Banner Title
            |--------------------------------------------------------------------------
            */

            title: {

                type: String,

                required: true,

                trim: true

            },


            /*
            |--------------------------------------------------------------------------
            | Banner Description
            |--------------------------------------------------------------------------
            */

            description: {

                type: String,

                trim: true,

                default: ""

            },


            /*
            |--------------------------------------------------------------------------
            | Banner Image
            |--------------------------------------------------------------------------
            */

            image: {

                type: String,

                required: true,

                trim: true

            },


            /*
            |--------------------------------------------------------------------------
            | Redirect URL
            |--------------------------------------------------------------------------
            */

            redirectUrl: {

                type: String,

                trim: true,

                default: ""

            },


            /*
            |--------------------------------------------------------------------------
            | Active Status
            |--------------------------------------------------------------------------
            */

            isActive: {

                type: Boolean,

                default: true

            },


            /*
            |--------------------------------------------------------------------------
            | Display Order
            |--------------------------------------------------------------------------
            */

            displayOrder: {

                type: Number,

                default: 0

            },


            /*
            |--------------------------------------------------------------------------
            | Start Date
            |--------------------------------------------------------------------------
            */

            startDate: {

                type: Date,

                default: null

            },


            /*
            |--------------------------------------------------------------------------
            | End Date
            |--------------------------------------------------------------------------
            */

            endDate: {

                type: Date,

                default: null

            },


            /*
            |--------------------------------------------------------------------------
            | Created By
            |--------------------------------------------------------------------------
            */

            createdBy: {

                type: mongoose.Schema.Types.ObjectId,

                ref: "User",

                required: true

            }

        },

        {

            timestamps: true

        }

    );


/*
|--------------------------------------------------------------------------
| Indexes
|--------------------------------------------------------------------------
*/

bannerSchema.index({

    isActive: 1,

    displayOrder: 1

});


bannerSchema.index({

    startDate: 1,

    endDate: 1

});


export const Banner =
    mongoose.model(
        "Banner",
        bannerSchema
    );